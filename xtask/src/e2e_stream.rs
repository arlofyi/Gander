//! `cargo xtask e2e-stream` (WP-57): Stream mode end to end against the test host, with
//! `gander-testwin` as the only application.
//!
//! 1. Builds the test-hooks host, the render worker, `gander-e2e` and `gander-testwin` (as
//!    `e2e-host` does) and copies them to `target/e2e/bin/`.
//! 2. Generates a share holding `stream/e2e.gtw` (the test host opens `.gtw` with
//!    `gander-testwin`, `--test-stream-app`) and starts the host on 127.0.0.1 port 0.
//! 3. Runs `gander-e2e stream` with its stdout wired to the host's stdin (`lock`, `unlock`,
//!    `kill`): the host stage (pair, `/v1/events`, `POST /v1/stream`, signalling, frames decoded
//!    with ffmpeg, the parked box in the decoded pixels, a tap that changes its colour, keepalive,
//!    pause/resume, lock, `DELETE ?close_app=true`, kill switch) and the engine stage (the capture
//!    path in process, and `engine.audio_tone`: a quiet 1 kHz tone from the test window through
//!    process loopback, Opus and the audio track, found within 5 Hz; all of it also runs while the
//!    session is locked). See
//!    `host/gander-e2e/src/stream.rs`.
//! 4. With `--android`: boots the `gander` AVD (only one emulator may run: it waits while another
//!    one is up), pairs a device for the stream share and runs `StreamViewerFixtureTest` against
//!    the same host, with the box position the host stage measured; `gander-e2e park-watch`
//!    parks each test window the phone opens (the host brings it to the front when the phone
//!    connects, and the client asks on `focus_lost`). The emulator is always killed.
//! 5. Writes `target/e2e/stream/report.json` (host output in `host.log`, Android output under
//!    `android/`), kills the host and every test window, and exits 1 on any failed step.
//!
//! The session must be unlocked and attended for anything that injects input: the host refuses
//! Stream while the computer is really locked. Locked, the host stage reports its session steps
//! `deferred: session locked`, the engine stage still runs, and the Android stage is deferred.

use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode, Stdio};
use std::time::{Duration, Instant};

use anyhow::{Context as _, Result, bail};

use crate::e2e::{self, HostProcess, TempTree, job};
use crate::e2e_android::{self as android, Emulator, Status};
use crate::preflight;
use crate::proc::{display_path, find_on_path, workspace_root};

const READY_TIMEOUT: Duration = Duration::from_secs(60);
const RUN_TIMEOUT: Duration = Duration::from_secs(900);
/// How long the Android stage waits for another worker's emulator to go away.
const EMULATOR_WAIT: Duration = Duration::from_secs(45 * 60);
const SHARE: &str = "shr_stream";
const FILE: &str = "stream/e2e.gtw";
/// The test host's catalogue entry for `gander-testwin` (`--test-stream-app`).
const APP: &str = "e2e-testwin";

#[derive(Debug, Default)]
struct Options {
    build: bool,
    android: bool,
    skip_engine: bool,
}

fn parse(args: &[String]) -> Result<Options> {
    let mut o = Options {
        build: true,
        ..Options::default()
    };
    for a in args {
        match a.as_str() {
            "--no-build" => o.build = false,
            "--android" => o.android = true,
            "--skip-engine" => o.skip_engine = true,
            other => bail!(
                "unknown option {other} (e2e-stream [--no-build] [--android] [--skip-engine])"
            ),
        }
    }
    Ok(o)
}

pub fn run(args: &[String]) -> Result<ExitCode> {
    let opts = parse(args)?;
    let root = workspace_root();
    let target = std::env::var_os("CARGO_TARGET_DIR")
        .map(PathBuf::from)
        .map(|t| if t.is_absolute() { t } else { root.join(t) })
        .unwrap_or_else(|| root.join("target"));
    let out = target.join("e2e").join("stream");
    let _ = std::fs::remove_dir_all(&out);
    std::fs::create_dir_all(&out)?;
    let report = out.join("report.json");

    if opts.build {
        e2e::build(&root)?;
    }
    let bin = e2e::install(&target.join("debug"), &target.join("e2e").join("bin"))?;
    let ffmpeg = find_on_path("ffmpeg");
    if ffmpeg.is_none() {
        eprintln!("note: ffmpeg is not on PATH; the decode steps will be deferred");
    }

    let work = TempTree::new()?;
    let share = work.path().join("share");
    std::fs::create_dir_all(share.join("stream"))?;
    std::fs::write(share.join(FILE), b"gander test window fixture (WP-57)")?;
    let config_dir = work.path().join("config");
    let data_dir = work.path().join("data");
    std::fs::create_dir_all(&config_dir)?;
    std::fs::create_dir_all(&data_dir)?;
    std::fs::write(
        config_dir.join("config.toml"),
        format!(
            "# Generated by cargo xtask e2e-stream.\nversion = 1\n\n[[share]]\nid = \"{SHARE}\"\nname = \"Stream E2E\"\nroot = '{}'\nstream_default = \"allowed\"\n",
            share.display()
        ),
    )?;

    let job = job::Job::new();
    let log_path = out.join("host.log");
    let grant = format!("{SHARE}=list,preview,fetch,stream");
    let mut host = HostProcess::start(
        &bin.host,
        &config_dir,
        &data_dir,
        &log_path,
        &job,
        &[&grant],
        Some(&bin.testwin),
    )?;
    let (addr, host_id) = match host.wait_ready(READY_TIMEOUT) {
        Ok(r) => r,
        Err(e) => {
            host.kill();
            bail!("{e:#} (host log: {})", display_path(&log_path));
        }
    };
    eprintln!("host ready on {addr}, pinned host id {host_id}");

    let box_file = out.join("box.json");
    let mut cmd = Command::new(&bin.suite);
    cmd.args(["stream", "--addr", &addr, "--host-id", &host_id])
        .args(["--share", SHARE, "--path", FILE, "--app", APP])
        .arg("--testwin")
        .arg(&bin.testwin)
        .arg("--report")
        .arg(&report)
        .arg("--work")
        .arg(out.join("work"))
        .arg("--box-out")
        .arg(&box_file)
        .stdin(Stdio::null())
        .stderr(Stdio::inherit());
    if let Some(f) = &ffmpeg {
        cmd.arg("--ffmpeg").arg(f);
    }
    if opts.skip_engine {
        cmd.arg("--skip-engine");
    }
    match host.child.stdin.take() {
        Some(stdin) => {
            cmd.stdout(Stdio::from(stdin));
        }
        None => {
            cmd.stdout(Stdio::null());
        }
    }
    let status = cmd
        .spawn()
        .context("start gander-e2e stream")
        .and_then(|mut child| {
            job.assign(&child);
            e2e::wait_timeout(&mut child, RUN_TIMEOUT)
        });

    // The Android stage needs the host's stdin no more (no lock or kill), only the host.
    let android = if opts.android {
        Some(android_stage(
            &root,
            &out.join("android"),
            &bin.suite,
            &addr,
            &host_id,
            &box_file,
            &job,
        ))
    } else {
        None
    };
    host.kill();
    drop(work);

    let code = status?;
    let text = std::fs::read_to_string(&report).with_context(|| {
        format!(
            "gander-e2e stream wrote no report at {}",
            display_path(&report)
        )
    })?;
    let mut value: serde_json::Value = serde_json::from_str(&text).context("report.json")?;
    let mut ok = code == Some(0) && value["summary"]["ok"] == true;
    if let Some(a) = android {
        let a = a.unwrap_or_else(|e| AndroidResult::fail(format!("{e:#}")));
        ok &= a.outcome != "fail";
        value["android"] = a.to_json();
        std::fs::write(&report, serde_json::to_vec_pretty(&value)?)?;
    }
    let s = &value["summary"];
    println!("report: {}", display_path(&report));
    println!(
        "steps: {} passed, {} failed, {} deferred (of {}); session at start: {}",
        s["passed"], s["failed"], s["deferred"], s["total"], value["session"]["at_start"]["state"]
    );
    if let Some(steps) = value["steps"].as_array() {
        for st in steps.iter().filter(|st| st["outcome"] != "pass") {
            println!("  {} {}: {}", st["outcome"], st["id"], st["detail"]);
        }
    }
    if !value["android"].is_null() {
        println!(
            "android: {} ({})",
            value["android"]["outcome"], value["android"]["detail"]
        );
    }
    if ok {
        println!("e2e-stream: OK");
        Ok(ExitCode::SUCCESS)
    } else {
        println!("e2e-stream: FAILED (gander-e2e stream exit {code:?})");
        Ok(ExitCode::from(1))
    }
}

// ---------------------------------------------------------------------------------- android

struct AndroidResult {
    /// `pass`, `fail` or `deferred`.
    outcome: &'static str,
    detail: String,
    tests: Vec<serde_json::Value>,
}

impl AndroidResult {
    fn fail(detail: String) -> Self {
        Self {
            outcome: "fail",
            detail,
            tests: Vec::new(),
        }
    }

    fn deferred(detail: &str) -> Self {
        Self {
            outcome: "deferred",
            detail: detail.to_owned(),
            tests: Vec::new(),
        }
    }

    fn to_json(&self) -> serde_json::Value {
        serde_json::json!({
            "outcome": self.outcome,
            "detail": self.detail,
            "class": android::STREAM_CLASS,
            "tests": self.tests,
        })
    }
}

/// The box position and tap result the host stage wrote (`--box-out`).
fn read_box(path: &Path) -> Option<(f64, f64, bool)> {
    let v: serde_json::Value = serde_json::from_slice(&std::fs::read(path).ok()?).ok()?;
    Some((
        v["box_x"].as_f64()?,
        v["box_y"].as_f64()?,
        v["tap"].as_bool().unwrap_or(false),
    ))
}

fn android_stage(
    root: &Path,
    out: &Path,
    suite: &Path,
    addr: &str,
    host_id: &str,
    box_file: &Path,
    job: &job::Job,
) -> Result<AndroidResult> {
    std::fs::create_dir_all(out)?;
    let Some((box_x, box_y, tapped)) = read_box(box_file) else {
        return Ok(AndroidResult::deferred(
            "deferred: the host stage measured no box position (session locked or the host stage failed)",
        ));
    };
    if !tapped {
        return Ok(AndroidResult::deferred(
            "deferred: the host stage's tap did not pass (session locked or input refused); the phone's tap would not either",
        ));
    }
    let sdk =
        preflight::android_sdk_root().context("ANDROID_HOME (or ANDROID_SDK_ROOT) is not set")?;
    let adb = preflight::adb_path(&sdk);
    let emulator = preflight::emulator_path(&sdk);
    let avd_home = preflight::avd_home();
    if !android::has_avd(&emulator, avd_home.as_deref()) {
        return Ok(AndroidResult::deferred(
            "deferred: needs emulator (no `gander` AVD)",
        ));
    }
    let gradlew =
        crate::testall::gradle_wrapper(root).context("no client/android Gradle project")?;
    android::gradle(
        root,
        &gradlew,
        &["assembleDebug", "assembleDebugAndroidTest"],
    )?;
    let apk_dir = root.join("client/android/app/build/outputs/apk");
    let app_apk = apk_dir.join("debug/app-debug.apk");
    let test_apk = apk_dir.join("androidTest/debug/app-debug-androidTest.apk");

    // One emulator at a time on this machine: wait for another worker's to go away.
    let waited = Instant::now();
    loop {
        let running = android::emulator_processes();
        if running.is_empty() {
            break;
        }
        if waited.elapsed() > EMULATOR_WAIT {
            return Ok(AndroidResult::deferred(&format!(
                "deferred: another emulator kept running for {} min ({})",
                EMULATOR_WAIT.as_secs() / 60,
                running.join(", ")
            )));
        }
        eprintln!(
            "waiting for another emulator to stop: {}",
            running.join(", ")
        );
        std::thread::sleep(Duration::from_secs(30));
    }

    // A device holding the stream grant; its token goes to the instrumentation only.
    let pair_file = out.join("pair.json");
    let st = Command::new(suite)
        .args(["pair", "--addr", addr, "--host-id", host_id])
        .args([
            "--name",
            "android stream",
            "--share",
            SHARE,
            "--perms",
            "list,stream",
        ])
        .arg("--out")
        .arg(&pair_file)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .status()
        .context("run gander-e2e pair")?;
    if !st.success() {
        bail!("gander-e2e pair failed");
    }
    let v: serde_json::Value = serde_json::from_slice(&std::fs::read(&pair_file)?)?;
    let _ = std::fs::remove_file(&pair_file);
    let token = v["token"].as_str().context("token")?.to_owned();
    let secrets = vec![token.clone()];
    let port = addr.rsplit(':').next().unwrap_or_default().to_owned();

    let adb_was_running = android::adb_server_running();
    let mut emu = Emulator::boot(&emulator, &adb, avd_home.as_deref(), out, job)?;
    let mut watcher = Command::new(suite)
        .args(["park-watch", "--seconds", "900"])
        .stdin(Stdio::null())
        .stdout(Stdio::from(std::fs::File::create(
            out.join("park-watch.txt"),
        )?))
        .stderr(Stdio::null())
        .spawn()
        .context("start gander-e2e park-watch")?;
    job.assign(&watcher);
    let run = (|| -> Result<android::Run> {
        emu.prepare(&[&app_apk, &test_apk])?;
        let args: Vec<(String, String)> = vec![
            ("gander.host.port".into(), port.clone()),
            ("gander.host.id".into(), host_id.to_owned()),
            ("gander.host.addresses".into(), "10.0.2.2".into()),
            ("gander.host.token".into(), token.clone()),
            ("gander.stream.share".into(), SHARE.into()),
            ("gander.stream.path".into(), FILE.into()),
            ("gander.stream.box_x".into(), format!("{box_x:.4}")),
            ("gander.stream.box_y".into(), format!("{box_y:.4}")),
            // The parked window is static: frames come at the keepalive rate.
            ("gander.stream.min_frames".into(), "10".into()),
            ("gander.stream.timeout_s".into(), "90".into()),
            ("class".into(), android::STREAM_CLASS.into()),
        ];
        eprintln!("==> {} on the emulator", android::STREAM_CLASS);
        let run = emu.instrument(&args, &out.join("instrument-stream.txt"), &secrets)?;
        if let Ok(log) = emu.adb_capture(&["logcat", "-d", "-v", "threadtime"]) {
            std::fs::write(out.join("logcat.txt"), android::redact(&log, &secrets))?;
        }
        Ok(run)
    })();
    let _ = watcher.kill();
    let _ = watcher.wait();
    let dead = emu.shutdown();
    if !adb_was_running {
        let _ = Command::new(&adb)
            .arg("kill-server")
            .stdin(Stdio::null())
            .output();
    }
    let run = run?;
    let tests: Vec<serde_json::Value> = run
        .tests
        .iter()
        .map(|t| {
            serde_json::json!({
                "test": format!("{}#{}", t.class, t.name),
                "status": match t.status {
                    Status::Passed => "passed",
                    Status::Failed => "failed",
                    Status::Skipped => "skipped",
                },
                "secs": t.secs,
                "message": t.message.as_deref().and_then(|m| m.lines().next()),
            })
        })
        .collect();
    let passed = run
        .tests
        .iter()
        .filter(|t| t.status == Status::Passed)
        .count();
    let ok = run.error.is_none() && run.tests.len() >= 2 && passed == run.tests.len() && dead;
    Ok(AndroidResult {
        outcome: if ok { "pass" } else { "fail" },
        detail: format!(
            "{passed} of {} passed{}; emulator stopped: {dead}",
            run.tests.len(),
            run.error
                .as_deref()
                .map(|e| format!(", run error: {e}"))
                .unwrap_or_default()
        ),
        tests,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn options() {
        let s = |v: &[&str]| v.iter().map(|x| (*x).to_owned()).collect::<Vec<_>>();
        let o = parse(&s(&["--no-build", "--android"])).unwrap();
        assert!(!o.build && o.android && !o.skip_engine);
        assert!(parse(&s(&["--bogus"])).is_err());
    }

    #[test]
    fn box_file_round_trip() {
        let dir = TempTree::new().unwrap();
        let p = dir.path().join("box.json");
        assert!(read_box(&p).is_none());
        std::fs::write(&p, r#"{"box_x":0.25,"box_y":0.4,"tap":true}"#).unwrap();
        assert_eq!(read_box(&p), Some((0.25, 0.4, true)));
    }
}
